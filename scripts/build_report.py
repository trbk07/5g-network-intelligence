"""Generate the experiment narrative and figures from committed results, never fit or replay."""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd


def table(frame):
    """Markdown without an optional tabulate dependency."""
    columns = list(frame.columns)

    def value(x):
        return f"{x:.6f}" if isinstance(x, float) else str(x)

    return "\n".join(
        ["| " + " | ".join(columns) + " |", "| " + " | ".join(["---"] * len(columns)) + " |"]
        + [
            "| " + " | ".join(value(v) for v in row) + " |"
            for row in frame.itertuples(index=False, name=None)
        ]
    )


