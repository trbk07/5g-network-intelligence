        "Common finite pairs align actuals, predictions, origins and beams. Pooled validation comparison contains 168/163/145 origins and 2880 beams at the respective horizons; see model_comparison_val.csv for exact coverage. Leakage tests perturb future observations; inference parity verifies saved batch forecasts against history-only inference.",
