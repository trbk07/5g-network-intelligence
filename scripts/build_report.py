        "Two seeds per variant were trained on hosted GPU. A uses target history, B adds the other KPIs; preprocessing and sampling follow the frozen contract. Seed means are distinct from ensemble-mean forecasts in the model comparison. Two seeds and this single dataset are limited evidence; C1 remained preferable on validation.",
